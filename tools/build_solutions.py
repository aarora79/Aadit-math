"""Build the password-locked question bank solutions page.

Reads the plain solutions HTML from private/ (not committed), base64-encodes it,
and writes docs/question-bank/solutions.html. The page decodes the content only
after the reader types the password.

This is a casual lock for a study site, not real security: anyone who decodes
the base64 in the page source can read the solutions.
"""

import argparse
import base64
import logging
from pathlib import Path


# Configure logging with basicConfig
logging.basicConfig(
    level=logging.INFO,  # Set the log level to INFO
    # Define log message format
    format="%(asctime)s,p%(process)s,{%(filename)s:%(lineno)d},%(levelname)s,%(message)s",
)
logger = logging.getLogger(__name__)

REPO_ROOT: Path = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE: Path = REPO_ROOT / "private" / "solutions-content.html"
DEFAULT_OUTPUT: Path = REPO_ROOT / "docs" / "question-bank" / "solutions.html"
DEFAULT_PASSWORD: str = "math-is-cool"

PAGE_TEMPLATE: str = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>Question bank solutions &middot; Aadit math</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<div class="wrap">

  <p class="eyebrow">MATHCOUNTS 2026 &middot; Practice</p>
  <h1>Question bank: hints and solutions</h1>
  <p style="font-size:14px"><a href="index.html" style="color:var(--teal);font-weight:600;text-decoration:none">&larr; Back to the questions</a></p>

  <form class="lockbox" id="lock">
    <label for="pw">This page needs a password.</label><br><br>
    <input id="pw" type="password" autocomplete="off">
    <button type="submit">Open</button>
    <p class="lockerror" id="lockerror" hidden>That is not the password. Try again.</p>
  </form>

  <div id="content"></div>

</div>
<script>
  // Generated by tools/build_solutions.py. Edit private/solutions-content.html and rebuild.
  var PASSWORD_B64 = "__PASSWORD_B64__";
  var CONTENT_B64 = "__CONTENT_B64__";
  document.getElementById("lock").addEventListener("submit", function (event) {
    event.preventDefault();
    var typed = document.getElementById("pw").value.trim();
    if (btoa(typed) !== PASSWORD_B64) {
      document.getElementById("lockerror").hidden = false;
      return;
    }
    document.getElementById("content").innerHTML = atob(CONTENT_B64);
    document.getElementById("lock").remove();
  });
</script>
</body>
</html>
"""


def _encode(
    text: str,
) -> str:
    """Return the base64 form of an ASCII string."""
    return base64.b64encode(text.encode("ascii")).decode("ascii")


def _read_source(
    source: Path,
) -> str:
    """Read the solutions HTML and make sure it is plain ASCII.

    The browser decodes with atob(), which only handles single-byte text, so
    special characters must be written as HTML entities (for example &minus;).
    """
    if not source.exists():
        raise FileNotFoundError(
            f"Solutions source not found at {source}. "
            "It lives only on the machine that built the site and is not committed."
        )
    text = source.read_text(encoding="utf-8")
    for line_number, line in enumerate(text.splitlines(), start=1):
        if not line.isascii():
            raise ValueError(
                f"{source}:{line_number} has a non-ASCII character. "
                "Use an HTML entity instead, for example &minus; or &deg;."
            )
    return text


def build_page(
    source: Path,
    output: Path,
    password: str,
) -> None:
    """Write the locked solutions page from the plain source file."""
    content = _read_source(source)
    page = PAGE_TEMPLATE.replace("__PASSWORD_B64__", _encode(password))
    page = page.replace("__CONTENT_B64__", _encode(content))
    output.write_text(page, encoding="utf-8")
    logger.info(f"Wrote {output} ({len(content)} characters of solutions)")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build the password-locked question bank solutions page.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Example usage:
    # Rebuild after editing private/solutions-content.html
    python3 tools/build_solutions.py
""",
    )
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE, help="Plain solutions HTML")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="Page to write")
    parser.add_argument("--password", default=DEFAULT_PASSWORD, help="Password readers must type")
    args = parser.parse_args()
    build_page(args.source, args.output, args.password)


if __name__ == "__main__":
    main()
